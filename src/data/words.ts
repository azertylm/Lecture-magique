function buildWorldWords(world: WorldId, tuples: RawWordTuple[]): WordItem[] {
  const pool = WORLD_DISTRACTOR_POOLS[world];
  return tuples.map(([id, emoji, art, word, syllables, silentLetter, phonemeHelp]) => {
    const distractors = pool.filter((e) => e !== emoji).slice(0, 6);
    return {
      id: `${world}_${id}`,
      emoji,
      art,
      word,
      syllables,
      ...(silentLetter ? { silentLetter } : {}),
      ...(phonemeHelp ? { phonemeHelp } : {}),
      distractors,
      world
    };
  });
}

